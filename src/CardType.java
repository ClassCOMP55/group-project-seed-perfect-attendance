/**
 * Represents the type of a card.
 * Card types are used by ObstacleScene to determine the outcome
 * when a card is played against an obstacle.
 */
public enum CardType {
    WAYFINDER,    // The Wayfinder card type
    SILVER_TONGUE, // The Silver Tongue card type
    HEARTSEEKER,  // The Heartseeker card type
    WILDCARD      // The Wildcard card type
}
